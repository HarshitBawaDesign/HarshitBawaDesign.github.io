"""Regenerate js/ratios.js (width/height of every tile cover in js/projects.js). Run after adding or swapping a cover."""
import re, subprocess, json, pathlib
from PIL import Image
site = pathlib.Path(__file__).resolve().parent.parent
s = (site / "js/projects.js").read_text()
R = {}
for c in sorted(set(re.findall(r'cover: M\("([^"]+)"\)', s))):
    f = site / "media" / c
    if c.endswith(".mp4"):
        o = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height", "-of", "csv=p=0", str(f)], capture_output=True, text=True).stdout.strip().split(",")
        w, h = map(int, o[:2])
    else:
        w, h = Image.open(f).size
    R["media/" + c] = round(w / h, 4)
(site / "js/ratios.js").write_text("/* auto-generated by tools/ratios.py: width/height of each tile cover, so tiles keep true proportions */\nconst RATIOS = " + json.dumps(R, indent=0) + ";\n")
print(len(R), "covers")
